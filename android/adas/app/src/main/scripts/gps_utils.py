#!/usr/bin/env python3
"""
Утилиты для работы с GPS координатами.
Конвертация GPS (lat, lon) в локальную систему координат (x, y).
"""
import numpy as np
from typing import Tuple, List


# Радиус Земли в метрах
EARTH_RADIUS = 6371000.0


def calculate_bearing(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """
    Вычисляет bearing (азимут) от точки 1 к точке 2 на сфере (Земле).

    Использует формулу сферической тригонометрии для расчета кратчайшего пути
    между двумя точками на поверхности Земли (дуга большого круга).

    Args:
        lat1, lon1: Широта и долгота первой точки (градусы)
        lat2, lon2: Широта и долгота второй точки (градусы)

    Returns:
        Bearing в градусах (0° = север, 90° = восток, 180° = юг, 270° = запад)

    Пример:
        # Москва → Санкт-Петербург
        bearing = calculate_bearing(55.7558, 37.6173, 59.9343, 30.3351)
        # bearing ≈ 318° (северо-запад)

    Формула (сферическая тригонометрия):
        x = sin(Δlon) * cos(lat2)
        y = cos(lat1) * sin(lat2) - sin(lat1) * cos(lat2) * cos(Δlon)
        bearing = atan2(x, y)

    Где:
        - x: восточная компонента направления
        - y: северная компонента направления
        - atan2(x, y): угол от севера (bearing)
    """
    # ШАГ 1: Конвертация из градусов в радианы
    # =========================================
    # Все тригонометрические функции работают с радианами
    lat1_rad = np.radians(lat1)
    lat2_rad = np.radians(lat2)
    dlon_rad = np.radians(lon2 - lon1)  # Δlon - разница долгот

    # ШАГ 2: Вычисление компонент направления (формула сферической тригонометрии)
    # ============================================================================
    # Эта формула учитывает кривизну Земли и даёт направление по кратчайшему пути

    # X-компонента (восточное направление):
    # -------------------------------------
    # sin(Δlon) - насколько сдвинулись по долготе
    #   > 0: движение на восток
    #   < 0: движение на запад
    # cos(lat2) - коррекция на широту (меридианы сходятся к полюсам!)
    #   На экваторе (lat=0°): cos(0°) = 1 (полный вклад)
    #   На полюсе (lat=90°): cos(90°) = 0 (меридианы сходятся в точку)
    x = np.sin(dlon_rad) * np.cos(lat2_rad)

    # Y-компонента (северное направление):
    # -------------------------------------
    # Более сложная формула, учитывающая сферическую геометрию:
    #   cos(lat1) * sin(lat2) - движение по широте
    #   sin(lat1) * cos(lat2) * cos(Δlon) - коррекция на кривизну Земли
    # Результат:
    #   > 0: движение на север
    #   < 0: движение на юг
    y = np.cos(lat1_rad) * np.sin(lat2_rad) - np.sin(lat1_rad) * np.cos(lat2_rad) * np.cos(dlon_rad)

    # ШАГ 3: Вычисление bearing через atan2
    # ======================================
    # atan2(x, y) определяет угол в полярных координатах:
    #   - Учитывает знаки x и y для определения квадранта
    #   - Возвращает угол от оси Y (север) в радианах
    #
    # Порядок аргументов ВАЖЕН: atan2(x, y), а НЕ atan2(y, x)!
    # Это даёт угол от севера (навигационная система координат)
    bearing_rad = np.arctan2(x, y)
    bearing_deg = np.degrees(bearing_rad)  # Конвертация обратно в градусы

    # ШАГ 4: Нормализация к диапазону [0°, 360°)
    # ===========================================
    # atan2 возвращает угол в диапазоне [-180°, 180°]
    # Приводим к стандартному навигационному формату [0°, 360°)
    bearing_deg = (bearing_deg + 360) % 360

    return bearing_deg


def calculate_initial_heading_from_gps(gps_data: np.ndarray, n_points: int = 5) -> float:
    """
    Рассчитывает начальную ориентацию (heading/yaw) автомобиля по первым GPS точкам.

    Этапы расчета:
    1. Берем первые N пар GPS точек
    2. Вычисляем bearing (азимут) между каждой парой
    3. Усредняем bearings (с учетом циклической природы углов)
    4. Конвертируем bearing (навигационный) в yaw (математический)

    Args:
        gps_data: numpy array shape (N, 5) [timestamp, lat, lon, alt, speed]
        n_points: Количество точек для усреднения (уменьшает шум GPS)

    Returns:
        Начальный yaw в радианах (0 = восток, π/2 = север, -π/2 = юг)

    Пример:
        gps_data = [[t1, 55.62, 37.65, ...], [t2, 55.63, 37.66, ...], ...]
        yaw = calculate_initial_heading_from_gps(gps_data, n_points=5)
        # yaw ≈ 1.075 рад (61.6°) = движение на северо-восток
    """
    if gps_data is None or len(gps_data) < 2:
        return 0.0

    # ЭТАП 1: Ограничить количество точек размером данных
    # ====================================================
    n_points = min(n_points, len(gps_data) - 1)

    # ЭТАП 2: Вычисляем bearing между каждой парой последовательных точек
    # ====================================================================
    # Bearing = азимут от севера (0°=север, 90°=восток, 180°=юг, 270°=запад)
    bearings = []
    for i in range(n_points):
        lat1 = gps_data[i, 1]  # Широта первой точки
        lon1 = gps_data[i, 2]  # Долгота первой точки
        lat2 = gps_data[i + 1, 1]  # Широта второй точки
        lon2 = gps_data[i + 1, 2]  # Долгота второй точки

        # Расчет bearing между точками (формула сферической тригонометрии)
        bearing = calculate_bearing(lat1, lon1, lat2, lon2)
        bearings.append(bearing)

    # ЭТАП 3: Усредняем bearing (правильное усреднение углов!)
    # =========================================================
    # ПРОБЛЕМА: Простое усреднение не работает для углов!
    #   Пример: mean([350°, 10°]) = 180° ❌ (неправильно, должно быть 0°)
    #
    # РЕШЕНИЕ: Усреднение через sin/cos (правильный метод)
    #   1. Представляем каждый угол как вектор на единичной окружности
    #   2. Усредняем x и y компоненты векторов
    #   3. Вычисляем угол результирующего вектора

    bearings_rad = np.radians(bearings)  # Конвертируем в радианы

    # Усреднение углов через векторное представление:
    #   angle → (cos(angle), sin(angle))  - вектор на единичной окружности
    mean_sin = np.mean(np.sin(bearings_rad))  # Среднее y-компонент
    mean_cos = np.mean(np.cos(bearings_rad))  # Среднее x-компонент
    mean_bearing_rad = np.arctan2(mean_sin, mean_cos)  # Угол результирующего вектора

    # ЭТАП 4: Конвертация bearing → yaw (смена системы координат)
    # =============================================================
    # Bearing (навигационная система):
    #   0° = Север, 90° = Восток, отсчет ПО ЧАСОВОЙ стрелке от севера
    #        N (0°)
    #        ↑
    #   W ←--+--→ E (90°)
    #        ↓
    #        S (180°)
    #
    # Yaw (математическая система):
    #   0° = Восток, 90° = Север, отсчет ПРОТИВ ЧАСОВОЙ стрелки от востока
    #        N (π/2)
    #        ↑
    #   W ←--+--→ E (0°)
    #        ↓
    #        S (-π/2)
    #
    # Формула конвертации: yaw = π/2 - bearing
    yaw_rad = np.pi / 2 - mean_bearing_rad

    # ЭТАП 5: Нормализация к диапазону [-π, π]
    # ==========================================
    # Приводим угол к стандартному диапазону
    while yaw_rad > np.pi:
        yaw_rad -= 2 * np.pi
    while yaw_rad < -np.pi:
        yaw_rad += 2 * np.pi

    return yaw_rad


def gps_to_local_coords(gps_data: np.ndarray, origin_idx: int = 0) -> Tuple[np.ndarray, np.ndarray]:
    """
    Конвертирует GPS координаты в локальную систему координат (X, Y в метрах).
    Использует Equirectangular projection (плоская проекция).

    Точность: Отлично для расстояний <100 км, приемлемо до 1000 км.
              Для больших расстояний используйте Haversine или UTM.

    Этапы конвертации:
    1. Выбор опорной точки (origin) как начала координат (0, 0)
    2. Вычисление разности координат (Δlat, Δlon) относительно origin
    3. Конвертация градусов в метры с коррекцией на широту

    Формула:
        y = Δlat × R × π/180  (север-юг)
        x = Δlon × cos(lat₀) × R × π/180  (запад-восток)

    Где:
        R = 6371000 м (радиус Земли)
        lat₀ = широта опорной точки
        Δlat = lat - lat₀
        Δlon = lon - lon₀

    Args:
        gps_data: numpy array shape (N, 5) [timestamp, lat, lon, alt, speed]
        origin_idx: Индекс опорной точки (обычно 0 - первая точка)

    Returns:
        Tuple (x_array, y_array) - координаты в метрах от опорной точки

    Пример:
        # GPS данные: [(t1, 55.62, 37.65, ...), (t2, 55.63, 37.66, ...)]
        x, y = gps_to_local_coords(gps_data, origin_idx=0)
        # x[0], y[0] = 0, 0 (опорная точка)
        # x[1], y[1] = смещение в метрах от первой точки
    """
    if gps_data is None or len(gps_data) == 0:
        return np.array([]), np.array([])

    # ЭТАП 1: Выбор опорной точки (начала координат)
    # ================================================
    lat0 = gps_data[origin_idx, 1]  # широта опорной точки (градусы)
    lon0 = gps_data[origin_idx, 2]  # долгота опорной точки (градусы)

    # Конвертация опорной широты в радианы (для cos)
    lat0_rad = np.radians(lat0)

    # ЭТАП 2: Извлечение всех координат
    # ==================================
    lats = gps_data[:, 1]  # Все широты
    lons = gps_data[:, 2]  # Все долготы

    # ЭТАП 3: Вычисление разности координат
    # ======================================
    # Разность широт (положительное = север, отрицательное = юг)
    dlat = lats - lat0
    # Разность долгот (положительное = восток, отрицательное = запад)
    dlon = lons - lon0

    # ЭТАП 4: Конвертация градусов в метры
    # =====================================
    # Формула Equirectangular projection:
    #
    # Y (север-юг):
    #   1° широты ≈ 111,320 м везде (меридианы параллельны)
    #   Формула: y = Δlat × R × π/180
    #   Где R×π/180 = 6371000×π/180 ≈ 111,320 м/градус
    #
    #   Почему постоянная?
    #   Все меридианы имеют одинаковую длину (20,004 км)
    #   → 1° широты = 20,004,000 м / 180° ≈ 111,133 м
    y = dlat * EARTH_RADIUS * np.pi / 180.0

    # X (запад-восток):
    #   1° долготы = cos(широта) × 111,320 м
    #   Формула: x = Δlon × cos(lat₀) × R × π/180
    #
    #   Почему cos(широта)?
    #   Параллели (линии широты) сходятся к полюсам:
    #     - На экваторе (lat=0°):  cos(0°)=1  → 1° долготы ≈ 111,320 м
    #     - На широте 45°:         cos(45°)≈0.707 → 1° долготы ≈ 78,710 м
    #     - На широте 60°:         cos(60°)=0.5   → 1° долготы ≈ 55,660 м
    #     - На полюсе (lat=90°):   cos(90°)=0     → 1° долготы = 0 м (точка!)
    #
    #   Пример для Москвы (lat ≈ 55.75°):
    #     cos(55.75°) ≈ 0.564
    #     1° долготы ≈ 111,320 × 0.564 ≈ 62,800 м
    x = dlon * np.cos(lat0_rad) * EARTH_RADIUS * np.pi / 180.0

    return x, y
